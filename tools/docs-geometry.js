// Writes docs/geometry.js: package/contents/code/geometry.js as a browser global `G`, for the
// landing page (GitHub Pages serves docs/ only). tests/geometry.test.js checks it is current.
//   node tools/docs-geometry.js
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');

function build() {
    const src = fs.readFileSync(path.join(ROOT, 'package', 'contents', 'code', 'geometry.js'), 'utf8')
        .replace(/^\.pragma library\n/m, '');
    const names = [...src.matchAll(/^(?:function|var)\s+(\w+)/gm)].map(m => m[1]);
    return '// Generated by tools/docs-geometry.js from package/contents/code/geometry.js; do not edit.\n'
        + 'var G = (function () {\n' + src + '\nreturn { ' + names.join(', ') + ' };\n})();\n';
}

if (require.main === module)
    fs.writeFileSync(path.join(ROOT, 'docs', 'geometry.js'), build());
module.exports = { build };
